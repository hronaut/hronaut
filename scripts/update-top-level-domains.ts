import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { isMainModule } from './is-main-module.ts'

/**
 * The address bar reads a dotted name whose last part is no top-level domain, such as `node.js`, as search terms, as
 * Chrome does with its list of known registries. This writes the list Hronaut knows from IANA's list of the root zone's
 * top-level domains: run `npm run update:top-level-domains` to take up domains IANA has added or removed since.
 */
export const IANA_TOP_LEVEL_DOMAINS_URL = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt'
export const TOP_LEVEL_DOMAINS_MODULE = fileURLToPath(new URL('../src/main/browser/top-level-domains.ts', import.meta.url))

const LINE_LENGTH = 120

/** The module holding IANA's list: its version, and its domains in lowercase, as the URL parser gives a host name. */
export function topLevelDomainsModule(list: string): string {
  const lines = list.split(/\r?\n/).map((line) => line.trim()).filter(Boolean)
  const version = /^# Version (\d+)/.exec(lines[0] ?? '')?.[1]
  if (!version) throw new Error('IANA\'s list of top-level domains starts with no version')
  const domains = lines.slice(1).map((line) => line.toLowerCase())
  const invalid = domains.find((domain) => !/^(?:[a-z]{2,}|xn--[a-z\d-]+)$/.test(domain))
  if (invalid !== undefined) throw new Error(`IANA's list of top-level domains holds an unexpected line: ${invalid}`)
  const unique = [...new Set(domains)].sort()
  if (unique.length < 1_000) throw new Error(`IANA's list of top-level domains holds only ${unique.length} domains`)
  const wrapped: string[] = []
  for (const domain of unique) {
    const last = wrapped.length - 1
    if (last >= 0 && wrapped[last]!.length + 1 + domain.length <= LINE_LENGTH) wrapped[last] += ` ${domain}`
    else wrapped.push(domain)
  }
  return [
    '// Generated by `npm run update:top-level-domains` from IANA\'s list of top-level domains,',
    `// ${IANA_TOP_LEVEL_DOMAINS_URL} (Version ${version}). Do not edit by hand.`,
    '',
    '/** The top-level domains of the DNS root zone, in lowercase, an internationalized one in its xn-- form. */',
    'export const TOP_LEVEL_DOMAINS: ReadonlySet<string> = new Set(`',
    ...wrapped,
    '`.trim().split(/\\s+/))',
    ''
  ].join('\n')
}

async function main(): Promise<void> {
  const response = await fetch(IANA_TOP_LEVEL_DOMAINS_URL)
  if (!response.ok) throw new Error(`IANA's list of top-level domains answered ${response.status}`)
  writeFileSync(TOP_LEVEL_DOMAINS_MODULE, topLevelDomainsModule(await response.text()))
}

if (isMainModule(import.meta.url)) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error)
    process.exitCode = 1
  })
}
